// Run from the repository root: node scripts/shinme-horse/shinme-horse-bake.mjs
// Set BLENDER_BIN to the Blender executable if it is not installed in /Applications.
// Offline only: the editable lofts are unified, then written into the runtime asset.
import {mkdtempSync,readFileSync,rmSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {addShinmeHorseSource} from './shinme-horse-source.mjs';

const directory=dirname(fileURLToPath(import.meta.url));
const scratch=mkdtempSync(join(tmpdir(),'shinme-bake-'));
try{
  const meshes=[];
  addShinmeHorseSource({put:geometry=>meshes.push(geometry)},{paper:null},0);
  const vertices=[],faces=[];
  for(const geometry of meshes){
    const position=geometry.attributes.position,index=geometry.index,offset=vertices.length;
    for(let i=0;i<position.count;i++)vertices.push([position.getX(i),-position.getZ(i),position.getY(i)]);
    for(let i=0;i<index.count;i+=3)faces.push([index.getX(i)+offset,index.getX(i+1)+offset,index.getX(i+2)+offset]);
    geometry.dispose();
  }
  const input=join(scratch,'source.json'),output=join(scratch,'form.json');
  writeFileSync(input,JSON.stringify({vertices,faces}));
  const executable=process.env.BLENDER_BIN??'/Applications/Blender.app/Contents/MacOS/Blender';
  const result=spawnSync(executable,['-b','-t','2','--python',join(directory,'shinme-horse-bake.py'),'--',input,output],{encoding:'utf8'});
  if(result.error)throw result.error;
  if(result.status!==0)throw Error(result.stderr||result.stdout);
  const baked=JSON.parse(readFileSync(output,'utf8'));
  const points=Buffer.alloc(baked.vertices.length*6),triangles=Buffer.alloc(baked.faces.length*6);
  baked.vertices.flat().forEach((n,i)=>points.writeInt16LE(Math.round(n*10000),i*2));
  baked.faces.flat().forEach((n,i)=>triangles.writeUInt16LE(n,i*2));
  const data=`// Generated by shinme-horse-bake.mjs from shinme-horse-source.mjs.\n`+
`import * as THREE from 'three';\n\n`+
`const positions='${points.toString('base64')}';\nconst indices='${triangles.toString('base64')}';\n\n`+
`function unpack(encoded,signed){\n  const binary=atob(encoded),bytes=Uint8Array.from(binary,c=>c.charCodeAt(0));\n`+
`  const view=new DataView(bytes.buffer),result=signed?new Float32Array(bytes.length/2):new Uint16Array(bytes.length/2);\n`+
`  for(let i=0;i<result.length;i++)result[i]=signed?view.getInt16(i*2,true)/10000:view.getUint16(i*2,true);\n  return result;\n}\n\n`+
`export function shinmeHorseForm(z){\n  const geometry=new THREE.BufferGeometry();\n`+
`  geometry.setAttribute('position',new THREE.BufferAttribute(unpack(positions,true),3));\n`+
`  geometry.setIndex(new THREE.BufferAttribute(unpack(indices,false),1));\n`+
`  geometry.translate(0,0,z);geometry.computeVertexNormals();return geometry;\n}\n`;
  writeFileSync(join(directory,'../../fushimi_inari/integrated-world/shinme-horse-form.mjs'),data);
  console.log(`Baked ${baked.vertices.length} vertices and ${baked.faces.length} triangles`);
}finally{rmSync(scratch,{recursive:true,force:true});}
