"""Reproducible adapter, preserving the original viewer as the source of details."""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parents[1]
source = (root / "interactive_viewer/index.html").read_text(encoding="utf-8")
body = source[source.index("    function applyMetricUVs"):source.index("    // 9. LOAD ALIGNED")]
# The measured terrain and cartographic paths replace only the compressed surfaces.
start = body.index("    const TERRAIN_W")
end = body.index("    /**", start)
body = body[:start] + body[end:]
body = re.sub(r"^    buildRibbonSegment\(.*?;\s*$", "", body, flags=re.M)
body = body.replace("const texLoader = new THREE.TextureLoader();",
                    "const texLoader = new THREE.TextureLoader(manager);")
body = body.replace("'assets/", "'../assets/")
body = body.replace("document.getElementById('torii-readout').textContent =",
                    "report.torii =")
body = body.replace("`${totalToriiCount} Torii (Caminos y Bifurcaciones 100% Despejados)`",
                    "totalToriiCount")
body = body.replace("document.getElementById('btn-toggle-map').textContent = '[M] Vista Local';",
                    "callbacks.map?.();")
for function,next_marker in [("createStoneLantern","// Create Wooden"),("createTrailSignboard","// 1.")]:
    start=body.index(f"    function {function}")
    end=body.index(next_marker,start)
    block=body[start:end].replace("scene.add(g);","g.userData.pathClearance=2.2; scene.add(g);")
    block=block.replace("scene.add(pl);","pl.userData.pathClearance=2.2; scene.add(pl);")
    body=body[:start]+block+body[end:]
# Capture scope on actual geometry and collision registrations, preserving groups.
scopes = {
    "buildConvergenceAprons": "okumiya", "buildTemizuya": "temizuya",
    "buildCourtyardFlankHalls": "gehaiden",
    "buildOmotesandoAndSurroundings": "entrance",
    "buildMainTempleAndOkumiyaConnection": "precinct",
    "buildOkushaZone": "okusha", "buildKumatakashaAndPond": "kumataka",
    "buildYotsutsujiCrossroads": "yotsu",
}
for function, zone in scopes.items():
    body = body.replace(f"    {function}();", f"    capture('{zone}', {function});")
# The original distant vista is illustrative, replaced by OSM/GSI surroundings.
body = body.replace("g.add(vistaGroup);", "report.replacedVista = true;")
for variable,zone in [("gg","gonden"),("tg","tamayama"),("okGroup","okumiya"),("byGroup","byakko"),("bGroup","senbon")]:
    body=body.replace(f"g.add({variable});",f"{variable}.userData.zone='{zone}'; g.add({variable});")
# Separate the two existing tea houses for individual map anchoring.
body=body.replace("g.add(chaya);","chaya.userData.zone=sideZ<0?'chaya_n':'chaya_s'; g.add(chaya);")
# The old whole-compound collider covered the public front steps. Preserve the
# stone terrace itself; use a rear enclosure collider rather than blocking entry.
body=body.replace("new THREE.Vector3(0, 0, -2.8)","new THREE.Vector3(0, 0, isSummit ? -7.5 : -5.7)")
body=body.replace("terraceW * 0.48,\n        terraceD * 0.46,","terraceW * 0.44,\n        terraceD * 0.23,")
start=body.index("      // Omokaru-ishi")
end=body.index("    buildOkushaZone",start) if "    buildOkushaZone" in body[start:] else body.index("    capture('okusha'",start)
block=body[start:end].replace("4.6","6.6").replace("3.6","5.6")
body=body[:start]+block+body[end:]
body = body.replace("scene.add(gzGroup);", "gzGroup.userData.zone='gozendani'; scene.add(gzGroup);")
body = body.replace("function createAuthenticPeakSanctuary(cfg) {",
    "function createAuthenticPeakSanctuary(cfg) {\n"
    "      const previousScope=scope; scope=cfg.isSummit?'summit':cfg.includeSwordRock?'mitsurugi':cfg.z<-250?'ninomine':'sannomine';")
# Restore scope after the last registration in the function.
marker = "\n    function buildUpperPeaksAndIchinomine()"
idx = body.index(marker)
previous = body.rfind("\n    }", 0, idx)
body = body[:previous] + "\n      scope=previousScope;" + body[previous:]
header = """// Generated by scripts/extract_legacy_builders.py; edit the adapter, not this file.
import * as THREE from 'three';
export async function buildLegacy(renderer, callbacks={}) {
  const scene=new THREE.Group(), report={}, colliders=[];
  const loaderStatus={set textContent(value){callbacks.progress?.(value)}};
  const loaderBar={style:{}};
  const minimapPanel={classList:{add(){callbacks.map?.()}}};
  const playBellChime=()=>callbacks.bell?.();
  const playWaterSplashSound=()=>callbacks.water?.();
  let scope=null;
  const rawAdd=scene.add.bind(scene);
  scene.add=(...objects)=>{for(const object of objects) if(!object.userData.zone)object.userData.zone=scope; return rawAdd(...objects);};
  function capture(name,fn){const old=scope;scope=name;fn();scope=old;}
  const collisionWorld={
    addCylinder(...args){colliders.push({type:'cylinder',args,zone:scope});},
    addBox(...args){colliders.push({type:'box',args,zone:scope});}
  };
  const failures=[];
  let finishTextures;
  const texturesReady=new Promise(resolve=>finishTextures=resolve);
  const manager=new THREE.LoadingManager(finishTextures,undefined,url=>failures.push(url));
"""
footer = """
  if(!callbacks.loadTexture)await texturesReady;
  if(failures.length)throw new Error('Missing original textures: '+failures.join(', '));
  return {scene,colliders,interactables,flickeringCandleMeshes,lanternPointLights,report,
    trailLookup,eastLoopLookup,sampleGroundHeight,
    materials:{vermilionMat,blackNemakiMat,stoneMat,flagstoneMat,gravelMat,plasterMat,
      copperRoofMat,goldMat,lanternGlowMat,roofMat},
    torii:{geometry:toriiVermGeo,blackGeometry:toriiBlackGeo,fresh:toriiFreshMat,weathered:toriiWeatheredMat},
    toriiMeshes:[instToriiFresh,instToriiWeathered,instToriiBlack],
    foliage:[instSugiTrunks,instSugiCrowns,instMomijiCrowns,instUnderstory,instBambooCulms,instBambooTops]};
}
"""
body = body.replace("const t = texLoader.load(url);", "const t = callbacks.loadTexture ? callbacks.loadTexture(url) : texLoader.load(url);")
out = root / "integrated-world"
out.mkdir(exist_ok=True)
(out / "legacy-builders.mjs").write_text(header + body + footer, encoding="utf-8")
(out / "legacy-source.sha256").write_text(hashlib.sha256(
    (root / "interactive_viewer/index.html").read_bytes()).hexdigest()+"\n")
collision=source[source.index("    class SpatialCollisionWorld"):source.index("    const collisionWorld")]
collision=collision.replace("cos: Math.cos(-yaw), sin: Math.sin(-yaw)","cos: Math.cos(yaw), sin: Math.sin(yaw)")
collision=collision.replace("cosF: Math.cos(yaw), sinF: Math.sin(yaw)","cosF: Math.cos(-yaw), sinF: Math.sin(-yaw)")
(out/"collision.mjs").write_text(collision.replace("class SpatialCollisionWorld","export class SpatialCollisionWorld",1),encoding="utf-8")
print("Extracted original builders; source untouched.")
